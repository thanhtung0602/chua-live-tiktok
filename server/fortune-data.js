export function stripVietnameseMarks(str = '') {
  return String(str)
    .toLowerCase()
    .split('')
    .map(c => NORMALIZE_MAP[c] || c)
    .join('')
    .replace(/[^a-z0-9\s]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Kiểm tra bình luận có phải yêu cầu gieo quẻ hay không
 */
export function isFortuneRequest(rawText = '') {
  const norm = stripVietnameseMarks(rawText);
  if (!norm) return false;

  const triggers = [
    'gieo que', 'xin que', 'boc que', 'rut que', 'xem que', 'lay que',
    'gieoque', 'xinque', 'que may man', 'xin xam', 'gieo xam'
  ];

  return triggers.some(t => norm.includes(t));
}

let lastFortuneIndex = -1;

/**
 * Rút một quẻ xăm ngẫu nhiên thông minh (tránh trùng quẻ vừa rút)
 */
export function drawRandomFortune() {
  let idx = Math.floor(Math.random() * FORTUNES.length);
  if (FORTUNES.length > 1 && idx === lastFortuneIndex) {
    idx = (idx + 1) % FORTUNES.length;
  }
  lastFortuneIndex = idx;
  return FORTUNES[idx];
}

/**
 * Tạo câu thoại AI đọc to trang nghiêm, truyền cảm và rõ chữ
 */
export function getFortuneSpeech(fortune, speakerName = 'Thiện hữu') {
  const cleanName = String(speakerName || 'Thiện hữu').replace(/^@+/, '').slice(0, 24);
  const numStr = String(fortune.number).padStart(2, '0');
  return `Nam Mô A Di Đà Phật. Xin chúc mừng Phật tử ${cleanName} đã gieo được Quẻ số ${numStr}, ${fortune.title}. Lời quẻ dạy rằng: ${fortune.speechSummary}. Nguyện cầu chư Phật gia hộ cho bạn và gia đình thân tâm thường an lạc, vạn sự hanh thông!`;
}
